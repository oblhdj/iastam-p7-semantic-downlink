def guard(fn, *args):
    """Run one section; a failure becomes a readable message, never a blank page."""
    try:
        fn(*args)
    except Exception as e:  # noqa: BLE001
        st.error(f"This section could not be rendered: {type(e).__name__}: {e}")
        with st.expander("Technical details"):
            st.code(traceback.format_exc())


def fmt_bytes(n) -> str:
    if n is None:
        return "—"
    n = float(n)
    return f"{n / 1e6:,.2f} MB" if n >= 1e6 else f"{n / 1e3:,.1f} kB" if n >= 1e4 else f"{n:,.0f} B"


def fmt_time(s) -> str:
    if s is None:
        return "—"
    return f"{s / 3600:,.2f} h" if s >= 3600 else f"{s:,.1f} s" if s >= 1 else f"{1e3 * s:,.2f} ms"


def fmt_energy(j) -> str:
    if j is None:
        return "—"
    return f"{j / 1e3:,.2f} kJ" if j >= 1e3 else f"{j:,.2f} J" if j >= 0.01 else f"{1e3 * j:,.2f} mJ"


def bars(df: pd.DataFrame, x: str, y: str, colour: str | None = None, log: bool = False,
         y_title: str | None = None, stack: bool = False, height: int = 280):
    """One-axis bar chart with hover values; `colour` names a categorical column."""
    scale = alt.Scale(type="log") if log else alt.Scale()
    enc = {"x": alt.X(f"{x}:N", sort=None, title=None, axis=alt.Axis(labelAngle=0)),
           "y": alt.Y(f"{y}:Q", scale=scale, title=y_title or y, stack="zero" if stack else None),
           "tooltip": [c for c in df.columns]}
    if colour:
        enc["color"] = alt.Color(f"{colour}:N", sort=None, title=None,
                                 scale=alt.Scale(range=[BLUE, ORANGE, AQUA, YELLOW]))
        if not stack:
            enc["xOffset"] = alt.XOffset(f"{colour}:N", sort=None)
    mark = alt.Chart(df).mark_bar(cornerRadiusTopLeft=3, cornerRadiusTopRight=3,
                                  color=BLUE)
    st.altair_chart(mark.encode(**enc).properties(height=height), width="stretch")


def table(rows, **kw):
    st.dataframe(pd.DataFrame(rows), hide_index=True, width="stretch", **kw)


def b64_image(b: str) -> bytes:
    return base64.b64decode(b)


