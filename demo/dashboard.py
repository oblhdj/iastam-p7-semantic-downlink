    data = name = labels = None
    kind, key = "swath", SWATH_KEY
    if src == "Bundled sample":
        if LIVE:
            tiles = sorted(p.name for p in (D.QUICKSTART / "tiles").glob("*.jpg"))
            choices = {SWATH_KEY: "3×3 synthetic swath, 2304 × 2304 px (shows SAHI against plain YOLO)"}
            choices.update({t: f"single tile — {t}" for t in tiles})
            if not tiles:
                st.error("No bundled tiles in demo/quickstart/tiles. Regenerate them with "
                         "`python demo/quickstart/make_synthetic_tiles.py`, or upload an image.")
                return
        else:
            choices = {s["key"]: s["title"] for s in fb_samples}
            if not choices:
                input_error = ("No static fallback assets: " + FB_INDEX.get("error", "none found")
                               + ". Create them on a working machine with `python demo/make_fallback_assets.py`.")
                st.error(input_error)
                return
        key = st.selectbox("Sample", list(choices), format_func=choices.get)
        kind = "swath" if key == SWATH_KEY else "tile"
        st.caption("The bundled samples are SYNTHETIC stand-ins: the Airbus competition rules forbid "
                   "redistributing the real tiles. They show that the chain runs; nothing computed "
                   "on them is a measurement.")
    else:
        up = st.file_uploader("Satellite image (JPEG, PNG, TIFF or BMP; 8-bit; up to "
                              f"{P.MAX_SIDE} px a side)", type=["jpg", "jpeg", "png", "tif", "tiff", "bmp"])
        gt = st.file_uploader("Optional ground truth (YOLO .txt: `0 cx cy w h`, normalised). "
                              "Without it no accuracy figure is shown.", type=["txt"])
        if up is None:
            input_error = "No image yet: upload one, or switch to a bundled sample."
            st.info(input_error)
            return
        kind, key, data = "upload", up.name, up.getvalue()
        if gt is not None:
            try:
                labels = gt.getvalue().decode("utf-8")
            except UnicodeDecodeError:
                st.error("The label file is not text (expected a YOLO .txt). It was ignored.")

    if LIVE:
        try:
            bundle, artifacts = compute(kind, key, data, labels, SETTINGS)
        except (ValueError, FileNotFoundError) as e:
            input_error = f"Image rejected: {e}" if kind == "upload" else str(e)
            st.error(input_error)
        except Exception as e:  # noqa: BLE001  the live run failed: say so, then fall back
            st.error(f"The live run failed: {type(e).__name__}: {e}")
            with st.expander("Technical details"):
                st.code(traceback.format_exc())
            LIVE = False
    if bundle is None and not LIVE:
        fb_key = Path(key).stem if kind == "tile" else key
        try:
            bundle, artifacts = D.load_fallback(fb_key)
            input_error = None
            st.warning(f"Showing STATIC results generated {bundle['meta']['generated_at']} at commit "
                       f"`{bundle['meta']['commit']}`. Nothing below was computed just now.")
            stale = D.fallback_staleness(FB_INDEX, CANON)
            if stale:
                st.warning("The committed results changed since these assets were generated "
                           "(the canonical numbers on this page are still read live): " + "; ".join(stale))
        except (FileNotFoundError, ValueError) as e:
            input_error = f"No static fallback for this input: {e}"
            st.error(input_error)
    if bundle is None:
        return

    i = bundle["input"]
    c1, c2 = st.columns([3, 2])
