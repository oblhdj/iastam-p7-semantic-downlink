def section_comms():
    st.subheader("F. Communication simulation")
    st.caption("SIM. Nothing here is a real satellite connection: orbits are propagated (SGP4), "
               "contact windows are geometry, rates come from a link-budget model, powers are assumptions.")
    mode, route = st.session_state.get("mode", "B3"), st.session_state.get("route", "policy")
    if need_image():
        comms = bundle["comms"]
        if comms.get("error"):
            st.error(f"The link simulation could not run ({comms['error']}). It needs the `skyfield` and "
                     f"`sgp4` packages: `python -m pip install -r demo/requirements-dashboard.txt`. "
                     f"The rest of the page is unaffected.")
        else:
            r = D.route_for(mode, route)
            run = comms["runs"][mode][r]
            st.markdown(f"**{D.MODE_INFO[mode]['title']}**, image captured at **{comms['capture_utc']} UTC** "
                        f"({comms['capture_h']:g} h after the simulated epoch).")
            c = st.columns(4)
            c[0].metric("Route", {"direct": "Direct", "policy": "Policy-chosen", "relay": "Relay"}[r])
            c[0].caption(f"Chosen by: {run['chosen_by']}." + ("" if D.MODE_INFO[mode]["relay"] else
                                                               f" {mode} has no relay."))
            c[1].metric("Path taken", f"{run['direct_items']} direct · {run['relay_items']} relay",
                        help="Items of this image that went down each path.")
            c[2].metric("Transmission duration", fmt_time(run["tx_s_total"]),
                        help="Time the transmitters are keyed for this image's bytes, at the physical link rate.")
            done = run["delivered_items"] == run["items"] and run["items"]
            c[3].metric("Capture → all on ground", fmt_time(run["latency_last_s"]) if done else
                        "not delivered" if run["items"] else "nothing to send",
                        help="Wait for the contact window(s) plus transmission.")
            if run["undelivered_items"]:
                st.warning(f"{run['undelivered_items']} of {run['items']} items were not delivered within the "
                           f"{comms['plan']['horizon_h']:g} h plan on this route (too large for the "
                           f"remaining pass capacity, or no window left).")
            elif not run["items"]:
                st.info("Nothing to send: this configuration produced no bytes for this image.")
            tx = run["tx_s"]
            st.caption("Transmit time by link — ground: " + fmt_time(tx["ground"]) + "; inter-satellite: "
                       + fmt_time(tx["isl"]) + "; relay's ground pass: " + fmt_time(tx["relay_ground"])
                       + ". The wait for a pass, not the transmission, is nearly all of the latency.")
            if run["deliveries"]:
                with st.expander(f"Every delivered item ({len(run['deliveries'])})"):
                    table(run["deliveries"], height=260)
            sw = comms.get("sweep")
            if sw:
                st.markdown("**Does the relay help? It depends on when the image is taken.** " + sw["what"] + ":")
                rows = [{"capture hour": x["capture_h"], "route": name, "hours": x[k]}
                        for x in sw["rows"] for k, name in (("direct_h", "direct only"), ("policy_h", "policy-chosen (may relay)"))
                        if x[k] is not None]
                df = pd.DataFrame(rows)
                st.altair_chart(alt.Chart(df).mark_line(point=alt.OverlayMarkDef(size=60), strokeWidth=2).encode(
                    x=alt.X("capture hour:Q", title="capture time (h after epoch)"),
                    y=alt.Y("hours:Q", title="capture → all on ground (h) [SIM]"),
                    color=alt.Color("route:N", title=None, scale=alt.Scale(range=[BLUE, ORANGE])),
                    tooltip=list(df.columns)).properties(height=260), width="stretch")
                med = df.groupby("route")["hours"].median()
                st.caption("Median over the 24 capture hours — " + "; ".join(f"{k}: {v:.2f} h" for k, v in med.items())
                           + ". One image on an otherwise empty link: no queue, no contention.")
            with st.expander("Link assumptions"):
                table([{"assumption": k, "value": str(v)} for k, v in comms["plan"]["assumptions"].items()])
                st.caption(comms["plan"]["assumption_label"])
            with st.expander("Contact plan (36 h)"):
                st.markdown("Primary satellite → ground station")
                table(comms["plan"]["primary_passes"])
                st.markdown("Relay satellite → ground station")
                table(comms["plan"]["relay_passes"])
                st.caption(f"{len(comms['plan']['isl_windows'])} inter-satellite windows in the same 36 h.")

    st.markdown("#### One image always fits. A whole day does not.")
    ss, h = CANON.get("steady_state"), CANON.get("headline")
    if not ss or not h:
        st.error("code/results/wp29_validation.json is missing, so the multi-day result cannot be shown.")
        return
    ours, fifo = ss["runs"]["share_0.25_Value-greedy (ours)"], ss["runs"]["share_0.25_FIFO"]
    rr = [d["ship_recall"] for d in ours["per_day"]]
    st.warning(
        f"A single image is a few kilobytes on an empty link, so it always completes. That is **not** "
        f"true of a nominal day: {ss['tiles_per_day']:,} tiles produce about **{h['MB_sent_per_day']:.0f} MB**, "
        f"and the link share sustains **{ours['sustained_capacity_MB_per_24h']} MB per 24 h** — the day offers "
        f"{100 * ours['offered_over_sustained']:.0f}% of capacity. The headline day is simulated alone with 36 h of "
        f"passes to drain it. Run {ss['days']} days back to back and the backlog is real:")
    c = st.columns(3)
    c[0].metric("Our scheduler: recall, every day", f"{min(rr):.3f}–{max(rr):.3f}")
    c[1].metric("Our scheduler: median latency",
                f"{min(d['latency_med_h'] for d in ours['per_day']):.1f}–{max(d['latency_med_h'] for d in ours['per_day']):.1f} h")
    c[2].metric("FIFO: median latency, day 1 → 6",
                f"{fifo['per_day'][0]['latency_med_h']:.1f} → {fifo['per_day'][-1]['latency_med_h']:.1f} h")
    df = pd.DataFrame([{"day": f"day {d['day']}", "policy": name, "median latency (h)": d["latency_med_h"],
                        "ship recall": d["ship_recall"]}
                       for name, run in (("value-greedy (ours)", ours), ("FIFO", fifo)) for d in run["per_day"]])
    g1, g2 = st.columns(2)
    with g1:
        bars(df, "day", "median latency (h)", colour="policy", y_title=f"median latency (h) [{ss['label']}]")
    with g2:
        bars(df, "day", "ship recall", colour="policy", y_title=f"ship recall [{ss['label']}]")
    st.caption(f"{ss['label']}, {ss['source']}. The value-greedy scheduler sheds bytes, not ships; FIFO falls "
               f"further behind each day and delivers {fifo['per_day'][-1]['ship_recall']:.3f} of day six's ships. One "
               f"assumption sits under the flat recall: a progressively truncated image counts as delivered "
               f"once it clears its minimum decodable fraction.")


